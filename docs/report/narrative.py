def a8_convergence_text(c):
    pts = c["a8c"]
    if len(pts) < 2:
        return ("The convergence runs (0.5 mm and 0.3 mm elements around the study's 0.4 mm) are "
                "still running; this section fills in when they finish.")
    rows = []
    base = dict(pts)
    for h, r in pts:
        rows.append(f"{h} mm ({r['mesh']['elements']} elements): torque at 90° "
                    f"{r['torque_n_mm']['90']:.3f} N·mm, peak interior strain "
                    f"{100 * r['peak_strain_interior']['90']:.1f} %")
    txt = "; ".join(rows) + ". "
    if 0.4 in base and min(base) < 0.4:
        fine = base[min(base)]
        d_t = (base[0.4]["torque_n_mm"]["90"] - fine["torque_n_mm"]["90"]) / fine["torque_n_mm"]["90"]
        d_e = (base[0.4]["peak_strain_interior"]["90"] - fine["peak_strain_interior"]["90"]) / fine["peak_strain_interior"]["90"]
        txt += (f"Between the study's 0.4 mm mesh and the finest, torque at 90° changes by "
                f"{100 * d_t:+.1f} % and peak strain by {100 * d_e:+.1f} %. ")
        txt += ("That is inside the 2 % criterion the project uses (Phase 3 criterion 3), so the "
                "A8 recommendation stands on a converged mesh." if abs(d_t) < 0.02 else
                "That is outside the 2 % criterion the project uses, so the A8 torques carry this "
                "mesh error; the ranking of A8 cases is unaffected because every case used the same mesh.")
    return txt


def round2_findings(c):
    """Bullet points drawn from whatever round-2 results exist."""
    r2 = c["r2"]
    out = list(R2_FINDINGS_STATIC)
    missing = [run for _, _, run, _ in SHORTLIST if run not in r2]
    if missing:
        out.append("Not yet run: " + ", ".join(sorted(set(missing))) + ".")
    return out


