HOOK_MM = 44.8
TENDON_D = {"as-built": 1.93, "deep": 3.40}
PIVOT_Y = {"B8_y20_r125": 2.0}       # dorsal pad lengthens the lever


def lever(run, d_key, variant):
    """Tendon lever (mm) about the joint at the run's pose, from the prediction table
    when available (it accounts for the pivot's position), else d."""
    return TENDON_D[d_key] + PIVOT_Y.get(variant, 0.0)


def hook_force(cap_T, lev):
    """Fingertip (hook) force at the PIP that a tendon tension cap_T can hold, ignoring
    the spring moment (small): T x lever = F x 44.8 mm."""
    return None if cap_T is None else cap_T * lev / HOOK_MM


