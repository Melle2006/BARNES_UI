HOOK_MM = 44.8
TENDON_D = {"as-built": 1.93, "deep": 3.40}
PIVOT_Y = {"B8_y20_r125": 2.0}       # dorsal pad lengthens the lever


def lever(run, d_key, variant):
    """Tendon lever (mm) about the joint at the run's pose, from the prediction table
    when available (it accounts for the pivot's position), else d."""
    return TENDON_D[d_key] + PIVOT_Y.get(variant, 0.0)


SERVO_T = 47.0


def hook_force(cap_T, lev):
    """Fingertip (hook) force at the PIP that a tendon tension cap_T can hold (capped at the
    servo's tension), ignoring the spring moment (small): T x lever = F x 44.8 mm."""
    return None if cap_T is None else min(cap_T, SERVO_T) * lev / HOOK_MM


def measured_basis(REPO):
    """(E measured, low, high, factor from the 12 MPa the studies were quoted at)."""
    b = json.loads((REPO / "results/sunlu_rescale/basis.json").read_text())
    em = b.get("E_sunlu_mpa") or 12.0
    lo, hi = b["E_bracket_mpa"]
    return em, lo, hi, em / 12.0


